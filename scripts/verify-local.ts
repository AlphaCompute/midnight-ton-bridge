import {readState} from '../src/environment.js';
import {writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {ledger} from '../build/midnight/contract/index.js';
import {openIndexer} from '../src/midnight-indexer.js';
import {verifyRedemption,type MidnightPins} from '../src/redemptions.js';
import {LOCAL_ESCROWS,LOCAL_TON_RECIPIENT,assertRoundTripLedger,rereadCalls} from './lib/round-trip.js';
const d=readState<{network:string;address:string;pins:MidnightPins}>('midnight-deployment.json');
if(d.network!=='undeployed')throw new Error('isolated local deployment required');
const p=openIndexer('local');
const verified=await rereadCalls(p,readState<{circuit:string;txId:string;blockHeight:number;status:string}[]>('local-proof-evidence.json'));
const state=await p.queryContractState(d.address,{type:'blockHash',blockHash:verified.at(-1)!.blockHash});if(!state)throw new Error('missing state');
const data=ledger(state.data);assertRoundTripLedger(data);
const id=[...data.retired][0]![0];
const request={id:Buffer.from(id).toString('hex'),asset:0 as const,amount:'100',recipient:LOCAL_TON_RECIPIENT.toRawString(),transactionId:verified.at(-1)!.txId};
verifyRedemption(state,d.pins,request,LOCAL_ESCROWS);
assert.throws(()=>verifyRedemption(state,d.pins,{...request,amount:'101'},LOCAL_ESCROWS),/differs/);
assert.throws(()=>verifyRedemption(state,{...d.pins,maintenanceHash:'00'.repeat(32)},request,LOCAL_ESCROWS),/maintenance/);
assert.throws(()=>verifyRedemption(state,{...d.pins,verifiers:{...d.pins.verifiers,claim:'00'.repeat(32)}},request,LOCAL_ESCROWS),/verifier/);
// --publish records this run as the repository's local evidence; a plain reproduction leaves it untouched.
if(process.argv.includes('--publish'))writeFileSync('docs/evidence/local-proof.json',JSON.stringify({network:'isolated-local-only',address:d.address,pins:d.pins,transactions:verified,final:{circulating:data.circulating.map(String),reserve:data.reserve.map(String),totalShares:String(data.totalShares),retiredCount:String(data.retired.size())},reverseVerification:'matched retirement; altered amount, maintenance authority and verifier rejected'},null,2)+'\n');
console.log('Six transactions independently re-read as successful; final balances and reverse observer checks passed.');
